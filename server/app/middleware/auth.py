"""Authentication middleware for API request validation"""

import logging
import secrets
from typing import Awaitable, Callable, Protocol

from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import JSONResponse, Response
from starlette.types import ASGIApp

from app.config import settings as default_settings

logger = logging.getLogger(__name__)


class AuthSettings(Protocol):
    """Protocol defining required auth settings."""

    auth_mode: str
    session_token: str
    auth_protect_docs: bool
    auth_protect_health: bool


class AuthMiddleware(BaseHTTPMiddleware):
    """
    Middleware for Bearer token authentication.

    Validates Authorization header against configured session token.
    Supports three modes:
    - disabled: No authentication required (development/legacy)
    - ephemeral: Token generated by the desktop app (Tauri) on each launch
    - static: Token configured via environment variable

    Configurable endpoint protection:
    - /api/health/ can be left open for health checks
    - /docs, /redoc, /openapi.json can be left open for API documentation
    """

    # Paths that are always unprotected (root info endpoint)
    ALWAYS_OPEN_PATHS = {"/"}

    def __init__(self, app: ASGIApp, settings: AuthSettings | None = None) -> None:
        super().__init__(app)

        # Use provided settings or fall back to global settings
        cfg = settings or default_settings

        self.token = cfg.session_token

        # Only enable auth if mode is set AND token is non-empty
        # This prevents empty-token bypass when misconfigured
        auth_mode_enabled = cfg.auth_mode in ("ephemeral", "static")
        token_configured = len(self.token) > 0

        if auth_mode_enabled and not token_configured:
            logger.warning(
                "Auth mode is '%s' but no session_token configured. "
                "Authentication is effectively disabled.",
                cfg.auth_mode,
            )

        self.auth_enabled = auth_mode_enabled and token_configured

        # Build dynamic skip paths based on config
        self.skip_paths: set[str] = set(self.ALWAYS_OPEN_PATHS)

        if not cfg.auth_protect_health:
            self.skip_paths.add("/api/health")
            self.skip_paths.add("/api/health/")

        if not cfg.auth_protect_docs:
            self.skip_paths.add("/docs")
            self.skip_paths.add("/redoc")
            self.skip_paths.add("/openapi.json")

    async def dispatch(
        self, request: Request, call_next: Callable[[Request], Awaitable[Response]]
    ) -> Response:
        # If auth is disabled, pass through
        if not self.auth_enabled:
            return await call_next(request)

        # Skip authentication for configured paths
        if request.url.path in self.skip_paths:
            return await call_next(request)

        # Validate Authorization header
        auth_header = request.headers.get("Authorization")

        if not auth_header:
            return JSONResponse(
                status_code=401,
                content={"detail": "Authentication required"},
            )

        # Parse Bearer token
        parts = auth_header.split(" ", 1)
        if len(parts) != 2 or parts[0].lower() != "bearer":
            return JSONResponse(
                status_code=401,
                content={"detail": "Authentication required"},
            )

        provided_token = parts[1]

        # Constant-time comparison to prevent timing attacks
        if not secrets.compare_digest(provided_token, self.token):
            return JSONResponse(
                status_code=401,
                content={"detail": "Authentication required"},
            )

        return await call_next(request)
