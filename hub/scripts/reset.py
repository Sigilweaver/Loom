#!/usr/bin/env python3
"""
Sigilweaver Loom Hub Reset Script

Wipes the database and regenerates all secrets for a clean development slate.

Usage (from app/hub/):
    uv run --directory backend python ../scripts/reset.py
    uv run --directory backend python ../scripts/reset.py --force
    uv run --directory backend python ../scripts/reset.py --no-seed
"""

import argparse
import os
import secrets
import subprocess
import sys
from pathlib import Path

from cryptography.fernet import Fernet
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

# ANSI color codes
GREEN = "\033[0;32m"
BLUE = "\033[0;34m"
RED = "\033[0;31m"
YELLOW = "\033[1;33m"
NC = "\033[0m"  # No Color


def get_hub_root() -> Path:
    """Find the hub root directory."""
    return Path(__file__).parent.parent.resolve()


def get_backend_root() -> Path:
    """Find the backend directory."""
    return get_hub_root() / "backend"


def print_banner() -> None:
    """Print the startup banner."""
    print(f"{RED}========================================{NC}")
    print(f"{RED}  Sigilweaver Loom Hub Reset Script{NC}")
    print(f"{RED}========================================{NC}")
    print()
    print(f"{YELLOW}WARNING: This will:{NC}")
    print("  - Stop and remove the PostgreSQL container")
    print("  - Delete all database data")
    print("  - Generate new encryption keys")
    print("  - Regenerate the .env file")
    print()


def confirm_reset() -> bool:
    """Ask for user confirmation."""
    response = input(f"{YELLOW}Are you sure you want to continue? [y/N]: {NC}")
    return response.lower() in ("y", "yes")


def generate_fernet_key() -> str:
    """Generate a new Fernet encryption key."""
    return Fernet.generate_key().decode()


def generate_session_secret() -> str:
    """Generate a secure session secret."""
    return secrets.token_urlsafe(32)


def generate_rsa_private_key() -> str:
    """Generate a new RSA private key for JWT signing."""
    private_key = rsa.generate_private_key(
        public_exponent=65537,
        key_size=2048,
    )
    pem = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    return pem.decode()


def stop_docker_services() -> None:
    """Stop and remove Docker containers and volumes."""
    hub_root = get_hub_root()
    print(f"{BLUE}Stopping Docker services...{NC}")

    # Stop containers
    subprocess.run(
        ["docker", "compose", "down", "-v"],
        cwd=hub_root,
        capture_output=True,
    )

    # Also try to remove any orphaned volumes
    subprocess.run(
        ["docker", "volume", "rm", "hub_postgres_data"],
        capture_output=True,
    )

    print(f"{GREEN}Docker services stopped and volumes removed{NC}")


def start_docker_services() -> None:
    """Start Docker services."""
    hub_root = get_hub_root()
    print(f"{BLUE}Starting Docker services...{NC}")

    result = subprocess.run(
        ["docker", "compose", "up", "-d"],
        cwd=hub_root,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        print(f"{RED}Failed to start Docker services:{NC}")
        print(result.stderr)
        sys.exit(1)

    print(f"{GREEN}Docker services started{NC}")

    # Wait for PostgreSQL to be ready
    print(f"{BLUE}Waiting for PostgreSQL to be ready...{NC}")
    import time
    for i in range(30):
        result = subprocess.run(
            ["docker", "compose", "exec", "-T", "postgres", "pg_isready", "-U", "sigilweaver_loom"],
            cwd=hub_root,
            capture_output=True,
        )
        if result.returncode == 0:
            print(f"{GREEN}PostgreSQL is ready{NC}")
            return
        time.sleep(1)
        print(f"  Waiting... ({i + 1}/30)")

    print(f"{RED}PostgreSQL failed to become ready{NC}")
    sys.exit(1)


def write_env_file(
    fernet_key: str,
    session_secret: str,
    jwt_private_key: str,
    server_secret: str,
) -> None:
    """Write the .env file with new secrets."""
    backend_root = get_backend_root()
    env_path = backend_root / ".env"

    # Escape the private key for .env format (multiline)
    # We'll use double quotes and escape newlines
    escaped_jwt_key = jwt_private_key.replace("\n", "\\n")

    env_content = f'''# Sigilweaver Loom Hub Backend Configuration
# Generated by reset.py - DO NOT COMMIT

# Database
DATABASE_URL=postgresql+asyncpg://sigilweaver_loom:sigilweaver_loom@localhost:25802/sigilweaver_loom_hub

# Session Authentication
SESSION_SECRET={session_secret}
SESSION_LIFETIME_HOURS=24

# JWT Signing Key for Server Tokens
JWT_PRIVATE_KEY="{escaped_jwt_key}"
JWT_ISSUER=sigilweaver-loom-hub
SERVER_TOKEN_TTL_SECONDS=300

# Connection Credential Encryption (Fernet)
CONNECTION_ENCRYPTION_KEY={fernet_key}

# Server Registration Secret
# Servers must provide this to register with Hub
SERVER_REGISTRATION_SECRET={server_secret}

# Development Settings
RELOAD=true
LOG_LEVEL=debug
CORS_ORIGINS=["http://localhost:25803"]
'''

    env_path.write_text(env_content)
    print(f"{GREEN}Created {env_path}{NC}")


def run_migrations() -> None:
    """Run database migrations."""
    backend_root = get_backend_root()
    print(f"{BLUE}Running database migrations...{NC}")

    result = subprocess.run(
        ["uv", "run", "alembic", "upgrade", "head"],
        cwd=backend_root,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        print(f"{RED}Failed to run migrations:{NC}")
        print(result.stdout)
        print(result.stderr)
        sys.exit(1)

    print(f"{GREEN}Migrations complete{NC}")


def seed_database() -> None:
    """Run the seed script to create initial data."""
    hub_root = get_hub_root()
    seed_script = hub_root / "scripts" / "seed_dev.py"

    if seed_script.exists():
        print(f"{BLUE}Seeding database...{NC}")
        result = subprocess.run(
            ["python", str(seed_script)],
            cwd=hub_root,
            capture_output=True,
            text=True,
        )

        if result.returncode != 0:
            print(f"{YELLOW}Seed script had issues (may be OK):{NC}")
            print(result.stdout)
            print(result.stderr)
        else:
            print(f"{GREEN}Database seeded{NC}")
    else:
        print(f"{YELLOW}No seed script found, skipping{NC}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Reset Sigilweaver Loom Hub to clean state")
    parser.add_argument(
        "--force", "-f",
        action="store_true",
        help="Skip confirmation prompt",
    )
    parser.add_argument(
        "--no-seed",
        action="store_true",
        help="Skip database seeding",
    )
    args = parser.parse_args()

    print_banner()

    if not args.force:
        if not confirm_reset():
            print("Reset cancelled.")
            sys.exit(0)

    print()

    # Step 1: Stop Docker services and remove volumes
    stop_docker_services()
    print()

    # Step 2: Generate new secrets
    print(f"{BLUE}Generating new secrets...{NC}")
    fernet_key = generate_fernet_key()
    session_secret = generate_session_secret()
    jwt_private_key = generate_rsa_private_key()
    server_secret = secrets.token_urlsafe(32)
    print(f"{GREEN}Secrets generated{NC}")
    print()

    # Step 3: Write .env file
    write_env_file(fernet_key, session_secret, jwt_private_key, server_secret)
    print()

    # Step 4: Start Docker services
    start_docker_services()
    print()

    # Step 5: Run migrations
    run_migrations()
    print()

    # Step 6: Seed database (optional)
    if not args.no_seed:
        seed_database()
        print()

    # Done
    print(f"{GREEN}========================================{NC}")
    print(f"{GREEN}  Hub reset complete!{NC}")
    print(f"{GREEN}========================================{NC}")
    print()
    print("Next steps:")
    print(f"  1. Start the dev servers: {BLUE}./scripts/dev.py{NC}")
    print(f"  2. Log in with: {YELLOW}testuser / testpass{NC} (admin)")
    print()


if __name__ == "__main__":
    main()
